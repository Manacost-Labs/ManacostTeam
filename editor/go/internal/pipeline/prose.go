package pipeline

func candidateRevisionInstruction(enabled bool) string {
	if !enabled {
		return ""
	}
	return "\nДОРАБОТКА ГОТОВОЙ РЕДАКЦИИ: source — исходное основание фактов; text — текущая редакция. " +
		"Используй независимый анализ source как карту задач и обязательств, затем отдельно проверь текущую редакцию относительно source. strengths взяты из исходника; текущие удачные формулировки и абзацы также сохраняй. " +
		"Редактируй текущую редакцию, не создавай заново текст из source. Исправляй конкретные ошибки, потерянные условия и степень, неудачные повторы и пустую обвязку; не заменяй равноценные ясные фразы. " +
		"Наличие предыдущей редакции не доказывает удачность каждой её правки. Сначала независимо сверь содержание с source, затем оцени каждое отличие по реальной пользе. Восстановление смысла не требует возвращать тяжёлый исходный синтаксис. Не склеивай полезные абзацы. Если улучшать нечего, верни текущую редакцию дословно."
}

func revisionBaseInstruction(base string) string {
	if base == "" {
		return ""
	}
	return "\nrevision_base — предыдущая редакция, не источник новых фактов и не объяснение автора. " +
		"Проверь также изменения candidate относительно неё: исправление исходника не оправдывает откат уже полезного сокращения, естественной фразы, авторской реакции или границы абзаца. " +
		"Смысл сверяй с source, качество доработки — с обеими версиями. Для нового ухудшения дай точное локальное finding и repair; improvements по-прежнему цитируют source → candidate."
}

// Craft guidance is not a detector score or a forbidden-word dictionary.
// Proofreading and facts-only modes keep their narrower contracts.
func proseInstruction(mode string) string {
	if mode != "edit" && mode != "rewrite" && mode != "reconstruct" {
		return ""
	}
	return "\nПиши в манере Манакоста через ход объяснения, а не набор примет. " +
		"У каждого абзаца есть вопрос читателя и конкретный ответ: что происходит, что выбрать, когда это работает и где ограничение — лишь в пределах известных фактов. " +
		"Пустое обобщение, обещание раскрыть потенциал, торжественное вступление и финал-пересказ не заменяют ответа. Если фраза повторяет заголовок или соседнюю мысль без новой пользы, убери именно дубль. " +
		"Не нанизывай одинаковые вводные, симметричные списки и связки «не только, но и» без смыслового противопоставления. Не заменяй конкретное действие абстрактными возможностями. Функциональный повтор термина, меры или условия сохраняй. " +
		"Риторические вопросы, обращения, сленг и образ нужны там, где помогают объяснить; не расставляй их по квоте. Сохраняй уместную авторскую реакцию, а не обезличивай текст автоматически. " +
		"Ритм следует мысли: короткая фраза выделяет решение, длинная связывает условие и причину. Не имитируй живость случайной рубкой, обрывками и искусственными ошибками. " +
		"Переход продолжает конкретную предыдущую мысль; новая глава снимает следующий вопрос. Не выдумывай личный опыт, причину, пример или уверенность ради плавности. " +
		"Образцы автора показывают приём и его функцию, не готовые предложения для заимствования. Проверяй точность, пользу и естественность, а не вероятность срабатывания ИИ-детектора."
}
