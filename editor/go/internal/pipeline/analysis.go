// Ordinary editing includes form work. Keep that intent out of proofreading,
// factual-only review and reconstruction, which have their own contracts.
func formEditingInstruction(mode string) string {
	if mode != "edit" && mode != "rewrite" {
		return ""
	}
	return "\nЗадача edit/rewrite: сохранить содержание и сделать его удобнее читать. Правильная мысль и удачный авторский голос совместимы с улучшением формы. " +
		"Оцени форму отдельно: смена функции внутри плотного абзаца, цепочка придаточных, тяжёлый пассив, избыточная словесная обвязка, повторение уже очевидной темы в соседних пунктах. " +
		"Разделяй самостоятельные смысловые шаги на абзацы, сохраняя связанное объяснение с его условием. Оценка ситуации, действие и отдельный дальнейший план могут образовывать разные абзацы даже в цельном комментарии одного автора. Атмосферная подводка и следующие за ней практические правила выполняют разные задачи: проверь границу между ними. Разделение не требует нового заголовка или переписывания слов. " +
		"Упрощай громоздкую фразу, когда та же мысль читается прямее: убирай дублирующую обвязку, сокращай цепочку придаточных, выбирай естественный глагол без выдуманного действующего лица. Сохраняй точный предмет, условия, степень уверенности и временную точку зрения. " +
		"Различай словесную обвязку и модальность оценки: возможность назвать или считать что-либо определённым не заменяй прямым утверждением. Указание на мнение автора само по себе не сохраняет снятую оговорку. При разделении абзаца оставляй её внутри оценки. " +
		"Проверь сочетание подлежащего со сказуемым и дублирующие определения внутри сильной мысли. Если исходник неудачно приписывает действие предмету, допустима естественная конструкция с уже однозначно подразумеваемым субъектом; новые участники, мотивы и действия недопустимы. Не исправляй живую понятную метафору только потому, что она переносная. " +
		qualifierExampleInstruction +
		"Для полезной правки достаточно небольшого конкретного выигрыша формы: легче найти отдельную мысль, короче синтаксическая связь, меньше повторной обвязки при ясном предмете. Новый факт, совет или объяснение для этого не нужны. " +
		"Перед добавлением пояснения проверь, что уже явно сказано в соседних предложениях. Если читатель уже получает это же правило, условие или порядок действий, оставь существующее объяснение и не пересказывай его ещё раз в другой фразе. Уточнение должно устранять реальную неоднозначность, а не повторять соседнее предложение. " +
		"Сравни целый абзац после правки: облегчение одной фразы не оправдывает появившийся рядом повтор. Оставь текст без изменений, если после проверки формы конкретной пользы нет."
}

// Delta review alone misses concrete readability problems carried over from
// the source. This belongs only to the editorial critic, not to every stage.
func formReviewInstruction(mode string) string {
	if mode != "edit" && mode != "rewrite" {
		return ""
	}
	return "\nПроверка оставшихся трудностей формы: прочитай весь candidate независимо от diff. " +
		"Сопоставь сведения соседних предложений: если определение повторяет уже выраженные время, новизну или количество и не отличает предмет от другого, убери только избыточное определение. Сохранённый из source плеоназм тоже требует оценки; наличие других удачных правок не повод его пропустить. Различай эту избыточность и значимую меру авторской оценки. " +
		"Для временной или качественной характеристики задай вопрос: какое отдельное сведение она даёт сверх даты, глагола и соседней фразы? Если ответа нет, небольшое сокращение убирает смысловой дубль и не требует нового содержания. Не смешивай эту микроправку с заменой одного равноценного синонима другим. Названия и важные определения не трогай. " +
		"Проверь смешение функций абзаца, неестественное сочетание субъекта и действия, дублирующие определения, а после сокращений — однокоренные повторы в соседних словах. Не считай исходную формулировку удачной лишь потому, что её не меняли. " +
		"Если конкретная трудность осталась и её можно устранить локально без нового содержания, верни repair с warning: дословно процитируй место в finding, назови затруднение читателя и ограничь требуемую правку этим местом. Сохрани остальные полезные изменения и границы абзацев. " +
		"Для границы абзаца назови две разные функции, а не длину. Для сокращения проверь, что не исчезнут предмет, условие, оговорка или авторская интонация. Уже понятное объяснение не расширяй; равноценный вариант и счётчик повторов не основание для repair. Нет обязательного числа замечаний: ясный candidate принимай. " +
		"Неприменённую правку не записывай в improvements; оставшийся недостаток source не называй новой регрессией candidate. improvements по-прежнему содержат только доказанные изменения source → candidate."
}

const qualifierExampleInstruction = "Учебный пример по функции слов, не факты для статьи: «Вчера начался новый фестиваль. На нём покажут новые фильмы». Если не утверждается, что фестиваль проводится впервые или отличается от прежнего, достаточно «Вчера начался фестиваль»; «новые фильмы» сообщает о самих фильмах и остаётся. Не объявляй все определения одним функциональным повтором: проверь каждое отдельно. При реальном противопоставлении старого и нового или признаке первого проведения определение сохраняется. "

// Analysis is advisory. A malformed optional field must not erase valid
// preservation evidence from another field. Accept the two observed object
// forms explicitly; never stringify arbitrary model objects into instructions.
func parseAnalysis(text string) Analysis {
	var fields map[string]json.RawMessage
	var out Analysis
	if err := json.Unmarshal([]byte(stripJSON(text)), &fields); err != nil || fields == nil {
		out.ParseWarnings = []string{"анализ не разобран: ожидается JSON-объект"}
		return out
	}
	for _, field := range []struct {
		name string
		dest *string
	}{{"thesis", &out.Thesis}, {"audience", &out.Audience}, {"genre", &out.Genre}} {
		if raw, ok := fields[field.name]; ok && json.Unmarshal(raw, field.dest) != nil {
			out.ParseWarnings = append(out.ParseWarnings, "неверный тип: "+field.name)
		}
	}
	for _, field := range []struct {
		name string
		dest *[]string
	}{{"paragraphs", &out.Paragraphs}, {"weak_spots", &out.WeakSpots}, {"repetitions", &out.Repetitions}, {"unclear", &out.Unclear}, {"template_phrases", &out.TemplatePhrases}, {"missing_links", &out.MissingLinks}, {"factual_risks", &out.FactualRisks}} {
		raw, ok := fields[field.name]
		if !ok {
			continue
		}
		var items []json.RawMessage
		if json.Unmarshal(raw, &items) != nil {
			out.ParseWarnings = append(out.ParseWarnings, "неверный тип: "+field.name)
			continue
		}
		for _, item := range items {
			var value string
			if json.Unmarshal(item, &value) != nil {
				var known struct {
					Function string `json:"function"`
					Where    string `json:"where"`
					Issue    string `json:"issue"`
				}
				if json.Unmarshal(item, &known) == nil {
					if field.name == "paragraphs" {
						value = known.Function
					}
					if field.name == "weak_spots" && known.Issue != "" {
						value = strings.TrimSpace(known.Where + ": " + known.Issue)
					}
				}
				if value == "" {
					out.ParseWarnings = append(out.ParseWarnings, "пропущен элемент: "+field.name)
				}
			}
			if strings.TrimSpace(value) != "" {
				*field.dest = append(*field.dest, value)
			}
		}
	}
	if raw, ok := fields["strengths"]; ok {
		var items []json.RawMessage
		if json.Unmarshal(raw, &items) != nil {
			out.ParseWarnings = append(out.ParseWarnings, "неверный тип: strengths")
		} else {
			for _, item := range items {
				var span StrongSpan
				if json.Unmarshal(item, &span) == nil {
					out.Strengths = append(out.Strengths, span)
				}
			}
		}
	}
	return out
}

